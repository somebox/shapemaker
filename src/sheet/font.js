/**
 * Single-stroke capitals and digits for engraved labels. Glyphs are open
 * polylines on a 4 × 6 grid (y up); a laser runs them as plain vector
 * lines, so no font has to exist on the machine.
 */

import { add, mul } from "./geom2.js";

const BOX = [[0, 0], [4, 0], [4, 6], [0, 6], [0, 0]];
const FIVE = [[[4, 6], [0, 6], [0, 3], [4, 3], [4, 0], [0, 0]]];

